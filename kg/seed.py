"""The hand-curated seed graph (HARM-S4-T03), assembled from the family files.

This is the part of the knowledge graph a reliability engineer would sign. The
extracted triples in `kg/extract.py` broaden it; this is what makes it correct.
Two things live here that extraction cannot supply:

- the `INDICATES` confidences, which are the ranking the diagnosis depends on.
  A confidence is a judgement about how specific a symptom is, and an extractor
  reading "elevated BPFO indicates outer-race wear" has no basis for choosing
  0.9 over 0.5.
- the `feature_kind` on each Symptom, which is the join back to the engine.
  It has to be exactly a `harmonic_feature_kind` enumerator, because
  `kg/query.py` matches the engine's surprised features against it by name.

The curated content itself is in `kg/families/*.json` (HARM-S7-T10).
`kg/seed.cypher` is GENERATED from this module (`python -m kg.seed --cypher`),
not maintained alongside it. Two hand-written copies of the same graph drift,
and the one that drifts is always the one nothing reads.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from kg import family_data
from kg.model import Graph, Node, Triple

SEED_CYPHER = Path(__file__).resolve().parent / "seed.cypher"

# The curated graph lives in data now, one file per machine family
# (`kg/families/*.json`, read by `kg/family_data.py`); this module assembles it
# and keeps the names the rest of the code imports.
_FAMILIES = family_data.by_family()

# The engine's trained class names mapped to the failure mode each one means:
# the strong prior in docs/KG_SCHEMA.md's join table — the class neuron says
# WHAT, the surprised features say WHY. Class names are a family's vocabulary:
# "misalignment" is the pump's motor coupling on P-101 and the gearbox input
# shaft on GB-201. A machine with no family reads the pump's table.
CLASS_TO_FAILURE_MODE: dict[str, str] = _FAMILIES[family_data.FIRST].classes
FAMILY_CLASS_TO_FAILURE_MODE: dict[str, dict[str, str]] = {
    name: f.classes for name, f in _FAMILIES.items()}

MANUAL_DOC = _FAMILIES[family_data.FIRST].manual


def build_seed() -> Graph:
    """The curated graph, without the ManualSection nodes.

    Those come from the chunk manifest in `kg/load.py`, so that a citation the
    graph offers is always a chunk the retriever can actually return.
    """
    nodes: list[Node] = []
    triples: list[Triple] = []
    for f in family_data.load_all():
        nodes += f.graph.nodes
        triples += f.graph.triples
    return Graph(nodes, triples)


# --- Cypher emission ----------------------------------------------------------

_CONSTRAINTS = """// Generated by `python -m kg.seed --cypher`. Do not edit.
//
// Uniqueness on `id` is what makes the loader idempotent: every write is a
// MERGE on id, so re-running after re-extracting updates rather than
// duplicates.
"""


def _lit(v: object) -> str:
    if isinstance(v, str):
        return "'" + v.replace("\\", "\\\\").replace("'", "\\'") + "'"
    if isinstance(v, bool):
        return "true" if v else "false"
    return str(v)


def to_cypher(graph: Graph) -> str:
    out: list[str] = [_CONSTRAINTS]
    from kg.model import NODE_LABELS
    for label in NODE_LABELS:
        out.append(f"CREATE CONSTRAINT {label.lower()}_id IF NOT EXISTS "
                   f"FOR (n:{label}) REQUIRE n.id IS UNIQUE;")
    out.append("CREATE INDEX sensor_kind IF NOT EXISTS FOR (n:Sensor) ON (n.kind);")
    out.append("CREATE INDEX symptom_kind IF NOT EXISTS FOR (n:Symptom) ON (n.feature_kind);")
    out.append("")

    for n in graph.nodes:
        props = ", ".join(f"n.{k} = {_lit(v)}" for k, v in sorted(n.props.items())
                          if v is not None)
        out.append(f"MERGE (n:{n.label} {{id: {_lit(n.id)}}})"
                   + (f"\n  SET {props};" if props else ";"))
    out.append("")

    labels = graph.node_labels()
    for t in graph.triples:
        props = ", ".join(f"{k}: {_lit(v)}" for k, v in sorted(t.props.items()))
        rel = f"[:{t.relation} {{{props}}}]" if props else f"[:{t.relation}]"
        out.append(
            f"MATCH (a:{labels[t.subject]} {{id: {_lit(t.subject)}}}), "
            f"(b:{labels[t.object]} {{id: {_lit(t.object)}}})\n"
            f"MERGE (a)-{rel}->(b);"
        )
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="The seed graph, assembled from kg/families/*.json")
    ap.add_argument("--cypher", action="store_true", help="regenerate kg/seed.cypher")
    ap.add_argument("--out", default=str(SEED_CYPHER))
    args = ap.parse_args(argv)

    from kg.load import manual_section_nodes
    from kg.model import validate_graph

    seed = build_seed()
    # Validated together with the ManualSection nodes, because the seed's
    # citation edges point into them and a dangling citation is the failure
    # this whole layer exists to prevent.
    full = seed.merge(Graph(manual_section_nodes(), []))
    validate_graph(full)

    if args.cypher:
        Path(args.out).write_text(to_cypher(full), encoding="utf-8")
        print(f"wrote {args.out}")
        return 0

    print(f"seed: {len(seed.nodes)} nodes, {len(seed.triples)} relations "
          f"(+{len(manual_section_nodes())} ManualSection nodes from the manifest)",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
